/**
 * 首页告警卡的**固定分页约束**（非组件文件，避免 react-refresh/only-export-components 告警）。
 *
 * 演进（用户 2026-09-18 反馈，含二次修订）：
 * - 一版：数据池「最新 8 条」固定渲染 8 行，卡高由页高压缩 → 矮窗口下出现卡内滚动条。
 * - 二版（已废弃）：为「整页不出现下拉进度条」，把每页行数由卡内**实测可用高度**反推
 *   （可用高度 → 行数），并配 `MainLayout fitViewport` 锁定「视口 − 顶部栏」。
 *   两个问题在真实环境暴露：
 *   ①页大小与视口高度耦合——同一数据在 1440×900 是 6 行、1440×1000 是 8 行，分页器时而出现、
 *     时而消失，版式随电脑/分辨率漂移，**没有稳定契约**；
 *   ②为「钉死一屏」不得不把告警卡拉伸到与右列等高，真实数据只有 1~2 条告警时，
 *     卡片下半部留下大片空白（用户反馈「空挡太多」）。
 * - 三版（本文件）：**与视口解耦的固定约束**——每页最多 `ALERT_PAGE_SIZE` 行，超出才出现分页器；
 *   卡片高度由内容决定（不测量、不拉伸、不占用剩余高度），页面按内容自然排布、超出视口即滚动。
 *
 * 行数取值（用户 2026-09-18 决策「方案乙」）：
 * 告警卡固定 5 行/页，「最近下发记录」固定 6 条，使左右两列在满数据时近似等高
 * （对齐手段与 min-height 兜底见 HomePage 双列区注释）。
 * 用户明确「更在意最近只显示 5 条这个契约」——告警列表的 5 行/页是硬契约，不随视口漂移。
 *
 * 数据池口径不变（决策 73「最新 8 条」）；分页只在池子超过单页上限时出现。
 */

/**
 * 单页最大行数：固定约束，不随视口/分辨率变化（改版式只改这一个常量）。
 *
 * 取值依据：两行制单行实测渲染高度约 52~54px，5 行 ≈ 270px；加上四格统计条、页脚参考行与卡头，
 * 满页卡高与右列（系统快速入口 + 最近下发 6 条）相当，既不让两列落差明显、也不显空旷。
 */
export const ALERT_PAGE_SIZE = 5

/**
 * 每页行数（纯函数，便于单测）：不超过池子大小，也不超过单页上限。
 * 池子 ≤ 上限时返回池子大小 → 分页器不出现（少量告警时保持单页观感）。
 */
export function computeAlertPageSize(total: number): number {
  if (!Number.isFinite(total) || total <= 0) return ALERT_PAGE_SIZE
  return Math.min(Math.floor(total), ALERT_PAGE_SIZE)
}
