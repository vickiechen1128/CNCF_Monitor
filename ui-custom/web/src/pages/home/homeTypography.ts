/**
 * 首页字号 / 字重阶梯（2026-10-17 第七轮走查定稿，产品负责人选定「标准档」）。
 *
 * 走查前实测：首页同时存在 **9 级字号**（11/12/13/14/15/16/18/20/24）与 **4 种字重**
 * （400/500/600/700），同一角色出现多种尺寸——「行级计数」有 18（云台数）/ 20（拨测四格）/
 * 14（采集图例）三套、「空态标题」有 14/700 ×3 与 15/600 一套、两个「整体率」圆环中心
 * 分别是 24/500 与 20/600。散点字号让版面看着「不像一套设计」，而不是某一块不好看。
 *
 * 收敛规则（6 级，一角色一尺寸）：
 * | 级别    | 尺寸/字重 | 唯一用途                                                  |
 * |---------|-----------|-----------------------------------------------------------|
 * | hero    | 24 / 600  | 圆环中心百分数（全页仅 2 处：纳管完成率、拨测正常率）        |
 * | primary | 20 / 600  | 告警四格主数字（当日 / 近 7 天 / 通知中 / 已静默·已抑制）    |
 * | title   | 16 / 600  | 卡标题、卡内分区标题、**行级计数**、空态标题                  |
 * | label   | 13 / 500  | 标签：表格资源类型、告警名、指标名、卡头深链                  |
 * | body    | 12 / 400  | 说明、单位、次行、**表头**、口径副标题                       |
 * | note    | 11 / 400  | 注释：卡底脚注、Prom 参考行、未处理提示                       |
 *
 * 字重口径：**数字一律 600**（24px 的 700 在大屏上偏「粗黑」，700 只作强调手段），
 * 700 仅保留给「合计」这一处（行列合计是全表唯一的闭合数）。
 *
 * 「行级计数一律 16」是本次最重要的一条：三张卡里的计数（云台数 / 采集四态 / 拨测四格）
 * 从此同尺寸同字重，横向扫读时数字等高，卡片之间才有「一套仪表盘」的整体感。
 *
 * 本文件只放常量（组件另见 TableHeaderText.tsx）——react-refresh 要求组件文件
 * 不与普通常量混导出，否则 HMR 会整页刷新。
 */

