package domain

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
)

// NewID returns a random RFC 4122 version-4 UUID used as the primary key of
// every M01 entity. IDs are opaque strings so they can travel through JSON and
// cross-module read models without numeric coercion.
func NewID() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", fmt.Errorf("generate m01 id: %w", err)
	}
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	return fmt.Sprintf("%s-%s-%s-%s-%s",
		hex.EncodeToString(b[0:4]),
		hex.EncodeToString(b[4:6]),
		hex.EncodeToString(b[6:8]),
		hex.EncodeToString(b[8:10]),
		hex.EncodeToString(b[10:16]),
	), nil
}
